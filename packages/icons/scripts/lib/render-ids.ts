import type { LibraryId } from "../../src/libraries";
import { LIBRARIES } from "../../src/libraries";
import type { IconEntry } from "../../src/types";

/**
 * Writes `src/ids.generated.ts`: every slug by library as one space-separated string, and the
 * slugs drawn as glyphs. The app checks ids and picks how to colour an icon from it, without
 * loading the full catalog.
 */
export function renderIds(entries: readonly IconEntry[]): string {
  const table = (pick: (entry: IconEntry) => boolean) =>
    LIBRARIES.map((library) => {
      const slugs = entries
        .filter((entry) => entry.library === library.id && pick(entry))
        .map((entry) => entry.slug)
        .join(" ");
      const value = JSON.stringify(slugs);
      return `  ${library.id satisfies LibraryId}:${keyBreak(library.id, value)}${value},`;
    }).join("\n");
  return [
    "// generated by scripts/build-catalog.ts — do not edit. Run `pnpm build:catalog` instead.",
    'import type { LibraryId } from "./libraries";',
    "",
    "/** Every catalog slug by library, space-separated. */",
    `export const ICON_SLUGS: Readonly<Record<LibraryId, string>> = {\n${table(() => true)}\n};`,
    "",
    "/** The slugs drawn as glyphs in `currentColor`, which take the canvas text colour. */",
    `export const GLYPH_SLUGS: Readonly<Record<LibraryId, string>> = {\n${table(
      (entry) => entry.kind === "glyph",
    )}\n};`,
    "",
  ].join("\n");
}

/**
 * Matches Prettier: a value that does not fit beside its key moves onto its own line, except
 * when the key is narrower than five columns (tab width plus three), where breaking gains little.
 */
function keyBreak(key: string, value: string): string {
  const fits = `  ${key}: ${value},`.length <= 100;
  return fits || key.length < 5 ? " " : "\n    ";
}
